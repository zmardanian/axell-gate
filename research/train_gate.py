"""Train Axell Gate's voice-activity network on the inputs computed by the SHIPPING C++ code (tools/GateFeatures.cpp).
Takes: corpus.take with random bleed, noise, breaths, recording chains, rooms and levels, at 44.1 / 48 / 96 kHz
(vad_data.job); 2.0: the 3 CMU ARCTIC voices and 24 VCTK voices. Held-out evaluation on each ARCTIC voice, then: Source/VoiceModel.h (all voices) and ~/axell-gate-data/models/no_<spk>.h.
usage: python3 train_gate.py <GateFeatures binary> [--eval-only]"""
import os, sys, subprocess, numpy as np
from concurrent.futures import ProcessPoolExecutor
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vad_data as VD

OUT = os.path.expanduser("~/axell-gate-data/gatefeat")
os.environ["AXG_VAD_OUT"] = OUT
K = 27                  # network inputs (VoiceActivity.h kVadInputs)
NC = 1 + K + 6
SPK = ("slt", "bdl", "jmk")

def fit(X, y, H=int(os.environ.get("AXG_H", 32)), epochs=int(os.environ.get("AXG_EP", 12)), seed=0, l2=1e-4, C3=3):
    rng = np.random.default_rng(seed); mu, sd = X.mean(0), X.std(0) + 1e-9; Z = (X - mu) / sd
    P = [rng.standard_normal((Z.shape[1], H)) / np.sqrt(Z.shape[1]), np.zeros(H), rng.standard_normal((H, C3)) / np.sqrt(H), np.zeros(C3)]
    M = [np.zeros_like(q) for q in P]; V = [np.zeros_like(q) for q in P]; t = 0; lr = 3e-3
    Yo = np.eye(C3)[y]
    for ep in range(epochs):
        idx = rng.permutation(len(Z))
        for s0 in range(0, len(Z), 4096):
            b = idx[s0:s0 + 4096]; z = Z[b]; h = np.tanh(z @ P[0] + P[1]); o = h @ P[2] + P[3]
            o -= o.max(1, keepdims=True); p = np.exp(o); p /= p.sum(1, keepdims=True)
            g = (p - Yo[b]) / len(b); gh = (g @ P[2].T) * (1 - h * h)
            G = [z.T @ gh + l2 * P[0], gh.sum(0), h.T @ g + l2 * P[2], g.sum(0)]; t += 1
            for i in range(4):
                M[i] = 0.9 * M[i] + 0.1 * G[i]; V[i] = 0.999 * V[i] + 0.001 * G[i] ** 2
                P[i] -= lr * (M[i] / (1 - 0.9 ** t)) / (np.sqrt(V[i] / (1 - 0.999 ** t)) + 1e-8)
        lr *= 0.75
    return P, mu, sd

def prob(X, m):
    P, mu, sd = m; h = np.tanh(((X - mu) / sd) @ P[0] + P[1]); o = h @ P[2] + P[3]
    o -= o.max(1, keepdims=True); p = np.exp(o); return p / p.sum(1, keepdims=True)

def write_header(path, m, nframes, what, prior):
    P, mu, sd = m
    f = lambda a: ", ".join(f"{v:.7g}f" for v in np.ravel(a))
    open(path, "w").write(f"""#pragma once
// Axell Gate - voice-activity network weights. GENERATED by research/train_gate.py from the inputs computed by the
// shipping C++ code (tools/GateFeatures.cpp) on CMU ARCTIC takes with headphone bleed, noise, breaths and recording
// chains at 44.1 / 48 / 96 kHz ({nframes} frames; {what}). Do not edit by hand.
// p = softmax(kB2 + kW2^T tanh(kB1 + kW1^T z)), z = (x - kMu) / kSd; classes: background, voice, breath
namespace axg::vmodel
{{
constexpr int kInputs = {P[0].shape[0]}, kHidden = {P[0].shape[1]};
constexpr float kPriorVoice = {prior:.4f}f; // share of voice frames in the training data (the decision divides by it)
constexpr float kMu[kInputs] = {{ {f(mu)} }};
constexpr float kSd[kInputs] = {{ {f(sd)} }};
constexpr float kW1[kInputs * kHidden] = {{ {f(P[0])} }};
constexpr float kB1[kHidden] = {{ {f(P[1])} }};
constexpr float kW2[kHidden * 3] = {{ {f(P[2])} }};
constexpr float kB2[3] = {{ {f(P[3])} }};
}} // namespace axg::vmodel
""")

if __name__ == "__main__":
    tool = sys.argv[1]
    os.makedirs(OUT, exist_ok=True)
    VD.OUT = OUT
    if "--eval-only" not in sys.argv:
        jobs = VD.jobs_list()
        with ProcessPoolExecutor() as ex:
            res = list(ex.map(VD.job, jobs))
        mans = []
        for i in range(12):
            mp = f"{OUT}/manifest{i}.txt"; open(mp, "w").writelines([r[0] for r in res][i::12]); mans.append(mp)
        procs = [subprocess.Popen([tool, m], stdout=subprocess.DEVNULL) for m in mans]
        assert all(p.wait() == 0 for p in procs)
        X, Y, S = [], [], []
        for line, (spk, k, fs, vlab, blab, xlab) in res:
            os.remove(line.split()[0])
            d = np.fromfile(f"{OUT}/{spk}_{k}.feat", np.float32).reshape(-1, NC).astype(np.float64)
            os.remove(f"{OUT}/{spk}_{k}.feat")
            X.append(d); Y.append(VD.labels_at(d[:, 0], vlab, blab, xlab)); S.append(np.full(len(d), spk))
        np.savez(f"{OUT}/all.npz", D=np.concatenate(X), Y=np.concatenate(Y), S=np.concatenate(S))
    z = np.load(f"{OUT}/all.npz")
    D, Y, S = z["D"], z["Y"], z["S"]
    keep = Y != 3                       # "don't care" frames (VCTK's filled short gaps) are left out
    print(f"{100 * (~keep).mean():.1f} % of the frames are don't-care (left out)")
    D, Y, S = D[keep], Y[keep], S[keep]
    X = D[:, 1:1 + K]
    print(f"{len(X)} frames: voice {100 * (Y == 1).mean():.1f} %, breath {100 * (Y == 2).mean():.1f} %")
    os.makedirs(os.path.expanduser("~/axell-gate-data/models"), exist_ok=True)
    for te in SPK:
        tr = np.where(S != te)[0][::2]
        m = fit(X[tr], Y[tr])
        write_header(os.path.expanduser(f"~/axell-gate-data/models/no_{te}.h"), m, len(tr), f"held-out fold: without {te}", float((Y[tr] == 1).mean()))
        sel = S == te; p = prob(X[sel], m); y = Y[sel]
        print(f"held-out {te}: accuracy {100 * ((p[:, 1] > 0.5) == (y == 1)).mean():.1f} % | voice missed {100 * (p[y == 1, 1] < 0.5).mean():.1f} % | "
              f"background as voice {100 * (p[y == 0, 1] > 0.5).mean():.1f} % | breath as voice {100 * (p[y == 2, 1] > 0.5).mean():.1f} % | "
              f"breath recognised {100 * (p[y == 2, 2] > 0.5).mean():.1f} %")
    m = fit(X[::2], Y[::2], epochs=int(os.environ.get("AXG_EP", 12)) + 2)
    hdr = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Source", "VoiceModel.h")
    write_header(hdr, m, len(X) // 2, "all voices", float((Y[::2] == 1).mean()))
    print("wrote", os.path.abspath(hdr))
